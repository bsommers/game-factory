// Client generator: OpenAPI 3 document (from api/server.mjs openapi()) -> typed thin clients for Go, Rust, Python.
// Pure: generate(doc, lang) returns { 'relative/path': 'content' }. Hand-written parts live in ./templates/<lang>/*.tmpl
// (a trailing .tmpl is stripped); the per-capability surface is emitted from the document. Deterministic output.
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

export const LANGS = ['go', 'rust', 'python'];
const TEMPLATES = new URL('./templates/', import.meta.url).pathname;

// Stable error.code set: every code the factory emits plus the transport-level ones the clients add themselves.
export const ERROR_CODES = ['BAD_CONFIG', 'BAD_INPUT', 'BAD_LOCK', 'CONFIRM_REQUIRED', 'CONFLICT', 'EXISTS', 'FAILED', 'FORBIDDEN', 'GH_FAILED', 'GIT_FAILED', 'IMPORT_FAILED', 'INTEGRITY', 'INTERNAL', 'INVALID', 'INVALID_THEME', 'MISSING_TEMPLATE', 'NOT_FETCHED', 'NOT_FOUND', 'NO_LOCK', 'NO_PROJECT', 'REGISTRY_ERROR', 'SECRETS_FOUND', 'STALE_INDEX', 'TAMPERED', 'TASK_FAILED', 'UNKNOWN_CAPABILITY', 'UNSAFE'];
export const CLIENT_CODES = ['TRANSPORT', 'BAD_RESPONSE']; // never sent by the server

const words = (s) => s.split(/[^A-Za-z0-9]+/).filter(Boolean);
const pascal = (s) => words(s).map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^A-Za-z0-9]+/g, '_').toLowerCase();
const oneLine = (s = '') => String(s).replace(/\s+/g, ' ').trim();
const RUST_KW = new Set(['type', 'ref', 'move', 'match', 'mod', 'use', 'fn', 'let', 'loop', 'impl', 'in', 'as', 'box', 'dyn', 'where', 'self', 'crate', 'super', 'struct', 'enum', 'trait', 'static', 'const', 'async', 'await', 'for', 'if', 'else', 'while', 'return', 'pub', 'mut', 'true', 'false', 'unsafe', 'extern']);
const PY_KW = new Set(['from', 'in', 'is', 'not', 'and', 'or', 'if', 'else', 'for', 'while', 'class', 'def', 'del', 'pass', 'global', 'lambda', 'None', 'True', 'False', 'with', 'as', 'try', 'except', 'import', 'return', 'yield', 'raise', 'assert', 'break', 'continue', 'finally', 'nonlocal', 'async', 'await', 'elif', 'self']);

// ---- model: capabilities from the document ------------------------------------------------------------
function scalar(s = {}) {
  if (s.enum) return 'string';
  const t = [].concat(s.type || []).filter((x) => x !== 'null');
  if (t.length !== 1) return 'any';
  if (t[0] === 'array') { const it = scalar(s.items || {}); return ['string', 'integer', 'number', 'boolean'].includes(it) ? `${it}[]` : 'any[]'; }
  return ['string', 'integer', 'number', 'boolean', 'object'].includes(t[0]) ? t[0] : 'any';
}
export function model(doc) {
  const caps = [];
  for (const [path, item] of Object.entries(doc.paths || {})) {
    const m = path.match(/^\/api\/(.+)$/); const op = item.post;
    if (!m || !op) continue;
    const schema = op.requestBody?.content?.['application/json']?.schema || {};
    const required = new Set(schema.required || []);
    const fields = Object.entries(schema.properties || {}).map(([key, s]) => ({
      key, kind: scalar(s), required: required.has(key), doc: oneLine(s.description || (s.enum ? `one of: ${s.enum.join(', ')}` : '')), enum: s.enum || null,
    })).sort((a, b) => (a.required === b.required ? (a.key < b.key ? -1 : 1) : a.required ? -1 : 1));
    caps.push({ name: m[1], summary: oneLine(op.summary), fields });
  }
  return caps.sort((a, b) => (a.name < b.name ? -1 : 1));
}

// ---- Go ---------------------------------------------------------------------------------------------------
const GO_T = { string: 'string', integer: 'int64', number: 'float64', boolean: 'bool', object: 'map[string]any', any: 'any', 'string[]': '[]string', 'integer[]': '[]int64', 'number[]': '[]float64', 'boolean[]': '[]bool', 'any[]': '[]any' };
function goCaps(caps) {
  const out = ['// Code generated by `factory clients generate --lang go` from GET /openapi.json. DO NOT EDIT.', '', 'package factoryclient', '', 'import "context"', ''];
  for (const c of caps) {
    const N = pascal(c.name);
    out.push(`// ${N}Input is the input of ${c.name}.`, `type ${N}Input struct {`);
    const rows = c.fields.map((f) => {
      const refType = !f.required && !/^(\[\]|map\[|any)/.test(GO_T[f.kind]);
      return [pascal(f.key), (refType ? '*' : '') + GO_T[f.kind], `\`json:"${f.key}${f.required ? '' : ',omitempty'}"\``, f.doc ? `// ${f.doc}` : ''];
    });
    const w = [0, 1, 2].map((k) => Math.max(0, ...rows.map((r) => r[k].length)));
    rows.forEach((r, i) => {
      let tw = 0; // gofmt aligns trailing comments only across a run of consecutive commented lines
      if (r[3]) { let a = i, b = i; while (a > 0 && rows[a - 1][3]) a--; while (b < rows.length - 1 && rows[b + 1][3]) b++; tw = Math.max(...rows.slice(a, b + 1).map((x) => x[2].length)); }
      out.push(`\t${r[0].padEnd(w[0])} ${r[1].padEnd(w[1])} ${r[3] ? r[2].padEnd(tw) + ' ' + r[3] : r[2]}`);
    });
    out.push('}', '', `// ${N} calls ${c.name}: ${c.summary}`, `func (c *Client) ${N}(ctx context.Context, in ${N}Input) (*Envelope, error) {`, `\treturn c.Call(ctx, "${c.name}", in)`, '}', '');
  }
  return out.join('\n');
}

// ---- Rust -------------------------------------------------------------------------------------------------
const RS_T = { string: 'String', integer: 'i64', number: 'f64', boolean: 'bool', object: 'serde_json::Value', any: 'serde_json::Value', 'string[]': 'Vec<String>', 'integer[]': 'Vec<i64>', 'number[]': 'Vec<f64>', 'boolean[]': 'Vec<bool>', 'any[]': 'Vec<serde_json::Value>' };
function rustCaps(caps) {
  const out = ['// Code generated by `factory clients generate --lang rust` from GET /openapi.json. DO NOT EDIT.', '', 'use crate::{Client, Envelope, Error};', 'use serde_json::{Map, Value};', ''];
  for (const c of caps) {
    const N = pascal(c.name); const fn = snake(c.name).replace(/_+/g, '_');
    out.push(`/// Input of \`${c.name}\`.`, '#[derive(Debug, Clone, Default, PartialEq)]', `pub struct ${N}Input {`);
    const names = c.fields.map((f) => { const s = snake(f.key); return RUST_KW.has(s) ? `r#${s}` : s; });
    c.fields.forEach((f, i) => out.push(...(f.doc ? [`    /// ${f.doc}`] : []), `    pub ${names[i]}: ${f.required ? RS_T[f.kind] : `Option<${RS_T[f.kind]}>`},`));
    out.push('}', '', `impl ${N}Input {`, '    pub fn to_json(&self) -> Value {', `        let${c.fields.length ? ' mut' : ''} m = Map::new();`);
    c.fields.forEach((f, i) => {
      if (f.required) out.push(`        m.insert("${f.key}".to_string(), serde_json::to_value(&self.${names[i]}).unwrap_or(Value::Null));`);
      else out.push(`        if let Some(v) = &self.${names[i]} { m.insert("${f.key}".to_string(), serde_json::to_value(v).unwrap_or(Value::Null)); }`);
    });
    out.push('        Value::Object(m)', '    }', '}', '', 'impl Client {', `    /// ${c.name}: ${c.summary}`, `    pub fn ${fn}(&self, input: &${N}Input) -> Result<Envelope, Error> {`, `        self.call("${c.name}", &input.to_json())`, '    }', '}', '');
  }
  return out.join('\n');
}

// ---- Python -----------------------------------------------------------------------------------------------
const PY_T = { string: 'str', integer: 'int', number: 'float', boolean: 'bool', object: 'dict', any: 'Any', 'string[]': 'list[str]', 'integer[]': 'list[int]', 'number[]': 'list[float]', 'boolean[]': 'list[bool]', 'any[]': 'list' };
const pyDoc = (s) => s.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"');
function pyCaps(caps) {
  const out = ['# Code generated by `factory clients generate --lang python` from GET /openapi.json. DO NOT EDIT.', 'from __future__ import annotations', '', 'from typing import Any', '', '', 'class Capabilities:', '    """One method per factory capability. Keyword arguments are the capability input; None is omitted."""', '',
    '    def call(self, name: str, input: dict | None = None):  # implemented by Client', '        raise NotImplementedError', ''];
  for (const c of caps) {
    const fn = snake(c.name).replace(/_+/g, '_');
    const pn = (f) => (PY_KW.has(f.key) ? `${f.key}_` : f.key);
    const args = c.fields.map((f) => `${pn(f)}: ${f.required ? PY_T[f.kind] : `${PY_T[f.kind]} | None = None`}`);
    out.push(`    def ${fn}(self${args.length ? ', *, ' + args.join(', ') : ''}):`, `        """${pyDoc(c.name + ': ' + c.summary)}"""`);
    out.push(`        return self.call("${c.name}", {${c.fields.map((f) => `"${f.key}": ${pn(f)}`).join(', ')}})`, '');
  }
  return out.join('\n');
}

// ---- assembly ---------------------------------------------------------------------------------------------
function walk(dir) { return readdirSync(dir).flatMap((n) => { const p = join(dir, n); return statSync(p).isDirectory() ? walk(p) : [p]; }); }

function codesFor(lang) {
  const all = [...ERROR_CODES, ...CLIENT_CODES].sort();
  if (lang === 'go') { const n = all.map((c) => `Err${pascal(c.toLowerCase())}`); const w = Math.max(...n.map((x) => x.length)); return all.map((c, i) => `\t${n[i].padEnd(w)} = "${c}"`).join('\n'); }
  if (lang === 'rust') return all.map((c) => `    pub const ${c}: &str = "${c}";`).join('\n');
  return all.map((c) => `    ${c} = "${c}"`).join('\n');
}

export function generate(doc, lang) {
  if (!LANGS.includes(lang)) throw new Error(`unknown lang "${lang}" (go|rust|python)`);
  const caps = model(doc); const version = doc.info?.version || '0.0.0';
  const files = {};
  const dir = join(TEMPLATES, lang);
  for (const f of walk(dir)) {
    const rel = relative(dir, f).replace(/\.tmpl$/, '');
    files[rel] = readFileSync(f, 'utf8').replaceAll('@@ERROR_CODES@@', codesFor(lang)).replaceAll('@@VERSION@@', version).replaceAll('@@COUNT@@', String(caps.length));
  }
  if (lang === 'go') files['capabilities.go'] = goCaps(caps);
  if (lang === 'rust') files['src/capabilities.rs'] = rustCaps(caps);
  if (lang === 'python') files['factory_client/capabilities.py'] = pyCaps(caps);
  return Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : 1)));
}
