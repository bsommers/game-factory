#!/usr/bin/env node
// Zero-dep CC0 asset fetcher (Poly Haven + ambientCG). Idempotent/resumable.
// Usage: node tools/fetch_assets.mjs [--only id1,id2] [--docs-only]
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = path.join(ROOT, 'tools/assets.manifest.json');
const CACHE = path.join(ROOT, 'assets-cache');
const TEX = path.join(ROOT, 'game/assets/textures');
const HDRI = path.join(ROOT, 'game/assets/hdri');
const STATE = path.join(CACHE, 'state.json');
const DOC = path.join(ROOT, 'docs/ASSETS.md');
const BUDGET = 3 * 1024 ** 3;
const args = process.argv.slice(2);
const only = args.includes('--only') ? args[args.indexOf('--only') + 1].split(',') : null;

const state = fs.existsSync(STATE) ? JSON.parse(fs.readFileSync(STATE, 'utf8')) : {};
const save = () => { fs.mkdirSync(CACHE, { recursive: true }); fs.writeFileSync(STATE, JSON.stringify(state, null, 1)); };

async function get(url, tries = 4) {
  for (let i = 1; ; i++) {
    try {
      const r = await fetch(url, { headers: { 'User-Agent': 'game-factory-asset-fetch/1.0' } });
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      return r;
    } catch (e) {
      if (i >= tries) throw new Error(`${url}: ${e.message}`);
      await new Promise(r => setTimeout(r, 1500 * i));
    }
  }
}
async function download(url, dest, md5) {
  const buf = Buffer.from(await (await get(url)).arrayBuffer());
  if (md5 && crypto.createHash('md5').update(buf).digest('hex') !== md5) throw new Error(`md5 mismatch ${url}`);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, buf);
  return buf.length;
}
const dirSize = d => fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).reduce((s, e) => s + (e.isDirectory() ? dirSize(path.join(d, e.name)) : fs.statSync(path.join(d, e.name)).size), 0) : 0;

// Poly Haven map key -> our file name
const PH_MAPS = { Diffuse: 'albedo', nor_gl: 'normal', Rough: 'roughness', AO: 'ao', Displacement: 'displacement', Metal: 'metallic' };
// ambientCG suffix -> our file name
const AC_MAPS = { Color: 'albedo', NormalGL: 'normal', Roughness: 'roughness', AmbientCG: null, AmbientOcclusion: 'ao', Displacement: 'displacement', Metalness: 'metallic' };

async function fetchPH(a) {
  const files = await (await get(`https://api.polyhaven.com/files/${a.assetId}`)).json();
  const out = [];
  if (a.kind === 'hdri') {
    const f = files.hdri?.['2k']?.hdr;
    if (!f) throw new Error('no 2k hdr');
    const dest = path.join(HDRI, `${a.id}_2k.hdr`);
    await download(f.url, dest, f.md5);
    out.push({ name: path.relative(ROOT, dest), url: f.url, size: fs.statSync(dest).size });
    return out;
  }
  for (const [key, name] of Object.entries(PH_MAPS)) {
    const f = files[key]?.['2k']?.jpg;
    if (!f) continue;
    const cache = path.join(CACHE, a.id, `${name}.jpg`);
    await download(f.url, cache, f.md5);
    const dest = path.join(TEX, a.id, `${name}.jpg`);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(cache, dest);
    out.push({ name: path.relative(ROOT, dest), url: f.url, size: fs.statSync(dest).size });
  }
  if (!out.length) throw new Error('no maps');
  return out;
}

async function fetchAC(a) {
  const url = `https://ambientcg.com/get?file=${a.assetId}_2K-JPG.zip`;
  const dir = path.join(CACHE, a.id);
  fs.mkdirSync(dir, { recursive: true });
  const zip = path.join(dir, 'src.zip');
  await download(url, zip);
  const ex = path.join(dir, 'x');
  fs.rmSync(ex, { recursive: true, force: true });
  execFileSync('unzip', ['-q', '-o', zip, '-d', ex]);
  const out = [];
  for (const f of fs.readdirSync(ex)) {
    const m = f.match(/_2K-JPG_(\w+)\.jpg$/);
    const name = m && AC_MAPS[m[1]];
    if (!name) continue;
    const dest = path.join(TEX, a.id, `${name}.jpg`);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(path.join(ex, f), dest);
    out.push({ name: path.relative(ROOT, dest), url, size: fs.statSync(dest).size });
  }
  if (!out.length) throw new Error('no maps in zip');
  fs.rmSync(ex, { recursive: true, force: true });
  return out;
}

function writeDoc(manifest) {
  const rows = [];
  let total = 0;
  for (const a of manifest.assets) {
    const s = state[a.id];
    if (!s) continue;
    for (const f of s.files) {
      total += f.size;
      rows.push(`| ${f.name} | ${a.source} (${a.assetId}) | ${f.url} | ${a.license} | ${(f.size / 1048576).toFixed(2)} MB |`);
    }
  }
  fs.mkdirSync(path.dirname(DOC), { recursive: true });
  fs.writeFileSync(DOC, `# Assets\n\nGenerated by \`tools/fetch_assets.mjs\` from \`tools/assets.manifest.json\`. All CC0 (Poly Haven, ambientCG). Max 2K.\n\nTotal in game/assets: ${(total / 1048576).toFixed(1)} MB across ${rows.length} files.\n\n| File | Source | URL | License | Size |\n|---|---|---|---|---|\n${rows.join('\n')}\n`);
}

const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
if (!args.includes('--docs-only')) {
  let failed = 0;
  for (const a of manifest.assets) {
    if (only && !only.includes(a.id)) continue;
    const done = state[a.id]?.files?.length && state[a.id].files.every(f => fs.existsSync(path.join(ROOT, f.name)));
    if (done) { console.log(`skip ${a.id}`); continue; }
    if (dirSize(CACHE) + dirSize(path.join(ROOT, 'game/assets')) > BUDGET) { console.error('budget exceeded'); process.exit(2); }
    try {
      const files = a.source === 'polyhaven' ? await fetchPH(a) : await fetchAC(a);
      state[a.id] = { files };
      save();
      console.log(`ok   ${a.id} (${files.length} files)`);
    } catch (e) { failed++; console.error(`FAIL ${a.id}: ${e.message}`); }
  }
  if (failed) console.error(`${failed} failed; re-run to resume`);
  process.exitCode = failed ? 1 : 0;
}
writeDoc(manifest);
